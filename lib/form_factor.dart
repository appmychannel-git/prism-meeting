import 'package:flutter/widgets.dart';

/// 큰 화면(태블릿/스탠드TV)인지 판정 — 휴대폰과 구분.
///
/// 용도: 휴대폰은 OS 공유 시트로 카톡·문자를 직접 보낼 수 있어 "공유 QR"이
/// 중복이므로 숨기고, 큰 화면(태블릿/TV)에서만 공유 QR(옆 휴대폰이 중계)을 쓴다.
///
/// 주의: 흔한 태블릿 기준(짧은 변 ≥ 600dp)만 쓰면 **1080p TV/스탠드가 빠진다.**
/// 1080p 화면은 보통 320dpi로 잡혀 논리 해상도가 960×540dp → 짧은 변이 540(<600).
/// 그래서 "가로로 넓은 큰 화면"(긴 변 ≥ 900 && 짧은 변 ≥ 500)도 큰 화면으로 본다.
/// - 휴대폰 세로 412×915: 짧은변 412<500 → 아님 ✓
/// - 휴대폰 가로 915×412: 짧은변 412<500 → 아님 ✓
/// - 1080p TV 960×540: 긴변 960≥900 & 짧은변 540≥500 → 큰 화면 ✓
/// - 태블릿 800×1280: 짧은변 800≥600 → 큰 화면 ✓
bool isBigScreen(BuildContext context) {
  final s = MediaQuery.of(context).size;
  return s.shortestSide >= 600 || (s.longestSide >= 900 && s.shortestSide >= 500);
}
